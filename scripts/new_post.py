#!/usr/bin/env python3
"""Create a report post (stamped image + skeleton) and regenerate nav / index pages."""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
import unicodedata
from pathlib import Path

import yaml

from watermark import WatermarkError, watermark

ROOT = Path(__file__).resolve().parent.parent
FM_KEYS = ["title", "date", "type", "keyword", "short", "image", "source", "x_caption"]
NAV_BEGIN = "# BEGIN NAV (generated by scripts/new_post.py — do not edit by hand)"
NAV_END = "# END NAV"
POSTS_BEGIN = "<!-- BEGIN POSTS -->"
POSTS_END = "<!-- END POSTS -->"

BODY = """# {title}

## The short answer

WRITE: 40–60 words that answer the question a searcher has about "{keyword}", with 1–2 numbers from the screenshot.

![{keyword} — ShotMatic report]({image})

## What the data shows

- WRITE: 3–5 bullets, each with a number and where it comes from.

## What this means if you build in this niche

WRITE: 2–3 sentences of advice for an indie app maker.

## How this was measured

{source}.

[Try ShotMatic free](https://shotmatic.app){{ .md-button .md-button--primary }}
"""


def load_types(root: Path = ROOT) -> dict[str, str]:
    return json.loads((root / "scripts" / "types.json").read_text())


def slugify(text: str, max_len: int = 60) -> str:
    ascii_text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_text.lower()).strip("-")
    if len(slug) > max_len:
        cut = slug[:max_len]
        slug = cut.rsplit("-", 1)[0] if "-" in cut and slug[max_len] != "-" else cut
    return slug.strip("-")


def read_post(path: Path) -> tuple[dict, str]:
    text = path.read_text()
    if not text.startswith("---\n"):
        raise ValueError(f"{path}: missing frontmatter")
    _, fm_text, body = text.split("---\n", 2)
    fm = yaml.safe_load(fm_text) or {}
    if "date" in fm:
        fm["date"] = str(fm["date"])
    return fm, body


def _write_post(path: Path, fm: dict, body: str) -> None:
    fm_text = yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000)
    path.write_text(f"---\n{fm_text}---\n\n{body}")


def _unique_slug(root: Path, type_: str, date: str, slug: str) -> str:
    folder = root / "docs" / type_
    candidate, n = slug, 2
    while (folder / f"{date}-{candidate}.md").exists():
        candidate, n = f"{slug}-{n}", n + 1
    return candidate


def create_post(root: Path, type_: str, date: str, slug: str, title: str,
                keyword: str, source: str, image_src: Path) -> dict:
    if type_ not in load_types(root):
        raise ValueError(f"unknown type {type_!r}; add it to scripts/types.json")
    try:
        dt.date.fromisoformat(date)
    except ValueError as e:
        raise ValueError(f"date must be YYYY-MM-DD, got {date!r}") from e
    slug = _unique_slug(root, type_, date, slugify(slug))
    folder = root / "docs" / type_
    image = watermark(Path(image_src), folder / "img", slug, date,
                      root / "docs" / "images" / "shotmatic-wordmark-light.png")
    rel_image = f"img/{image.name}"
    fm = {
        "title": title,
        "date": date,
        "type": type_,
        "keyword": keyword,
        "short": slug.replace("-", " ").capitalize(),
        "image": rel_image,
        "source": source,
        "x_caption": "",
    }
    post = folder / f"{date}-{slug}.md"
    _write_post(post, fm, BODY.format(title=title, keyword=keyword, image=rel_image, source=source.rstrip(".")))
    rebuild_site(root)
    return {"slug": slug, "post": str(post), "image": str(image)}


def _posts_by_type(root: Path) -> dict[str, list[tuple[dict, Path]]]:
    out: dict[str, list[tuple[dict, Path]]] = {}
    for type_ in load_types(root):
        items = []
        for p in sorted((root / "docs" / type_).glob("*.md")):
            if p.name == "index.md":
                continue
            fm, _ = read_post(p)
            items.append((fm, p))
        items.sort(key=lambda it: (it[0]["date"], it[1].name), reverse=True)
        if items:
            out[type_] = items
    return out


def _short_date(d: str) -> str:
    x = dt.date.fromisoformat(d)
    return f"{x:%b} {x.day}"


def _long_date(d: str) -> str:
    x = dt.date.fromisoformat(d)
    return f"{x:%b} {x.day}, {x.year}"


def _replace_block(text: str, begin: str, end: str, inner: str) -> str:
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{begin}\n{inner}{end}{tail}"


def rebuild_site(root: Path = ROOT) -> None:
    types = load_types(root)
    by_type = _posts_by_type(root)

    nav = ["nav:", "  - Home: index.md"]
    for type_, items in by_type.items():
        nav.append(f"  - {types[type_]}:")
        nav.append(f"      - {type_}/index.md")
        for fm, p in items:
            label = json.dumps(f"{_short_date(fm['date'])} · {fm['short']}", ensure_ascii=False)
            nav.append(f"      - {label}: {type_}/{p.name}")
    yml_path = root / "mkdocs.yml"
    yml_path.write_text(_replace_block(yml_path.read_text(), NAV_BEGIN, NAV_END, "\n".join(nav) + "\n"))

    all_posts = sorted(
        ((fm, p, type_) for type_, items in by_type.items() for fm, p in items),
        key=lambda it: (it[0]["date"], it[1].name), reverse=True,
    )
    lines, current = [], None
    for fm, p, type_ in all_posts:
        if fm["date"] != current:
            current = fm["date"]
            lines += ["", f"### {_long_date(current)}", ""]
        lines.append(f"- [{fm['title']}]({type_}/{p.name}) · {types[type_]}")
    inner = ("\n".join(lines).lstrip("\n") if lines else "_No reports yet._") + "\n"
    home = root / "docs" / "index.md"
    home.write_text(_replace_block(home.read_text(), POSTS_BEGIN, POSTS_END, inner))

    for type_, items in by_type.items():
        body = [f"# {types[type_]} reports", ""]
        body += [f"- {_long_date(fm['date'])} · [{fm['title']}]({p.name})" for fm, p in items]
        (root / "docs" / type_ / "index.md").write_text("\n".join(body) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("create")
    c.add_argument("--type", required=True)
    c.add_argument("--slug", required=True)
    c.add_argument("--title", required=True)
    c.add_argument("--keyword", required=True)
    c.add_argument("--source", required=True)
    c.add_argument("--image", type=Path, required=True)
    c.add_argument("--date", default=dt.date.today().isoformat())
    sub.add_parser("nav")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "create":
            r = create_post(ROOT, a.type, a.date, a.slug, a.title, a.keyword, a.source, a.image)
            print(json.dumps(r, indent=2))
        else:
            rebuild_site(ROOT)
    except (ValueError, WatermarkError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
